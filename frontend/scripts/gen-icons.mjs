// Writes src/components/ionicons.gen.ts: the inner SVG of every Ionicons glyph the app
// uses (MIT, https://ionic.io/ionicons), so the bundle carries only these and a build
// never needs the package. Run from frontend/: node scripts/gen-icons.mjs
// To use another glyph, add its name below, run this, and map it in components/icons.tsx.
import { readFileSync, writeFileSync } from 'node:fs'

const NAMES = [
  // components/icons.tsx
  'add', 'arrow-forward', 'bar-chart-outline', 'battery-charging-outline', 'bug-outline', 'build-outline',
  'business-outline', 'cafe-outline', 'calendar-outline', 'call-outline', 'car-sport-outline', 'cash-outline',
  'chatbubble-outline', 'checkmark', 'checkmark-circle-outline', 'chevron-back', 'chevron-down', 'chevron-forward',
  'chevron-up', 'clipboard-outline', 'close', 'copy-outline', 'download-outline', 'ellipsis-horizontal', 'flame',
  'flash', 'funnel-outline', 'grid-outline', 'hand-left-outline', 'help-buoy-outline', 'hourglass-outline',
  'information-circle-outline', 'key-outline', 'leaf', 'list-outline', 'locate-outline', 'location-outline',
  'log-out-outline', 'mail-outline', 'map-outline', 'menu', 'moon-outline', 'navigate-outline',
  'notifications-outline', 'options-outline', 'pencil-outline', 'people-outline', 'person-outline', 'remove',
  'reorder-two-outline', 'repeat-outline', 'search-outline', 'send', 'share-outline', 'shield-checkmark-outline',
  'shield-outline', 'speedometer-outline', 'sunny-outline', 'time-outline', 'trail-sign-outline', 'trash-outline',
  'water',
  // components/NavIcon.tsx: the filled twins of the navigation marks
  'battery-charging', 'book', 'book-outline', 'bug', 'business', 'calendar', 'car-sport', 'clipboard', 'download',
  'grid', 'help-buoy', 'list', 'map', 'notifications', 'people', 'person', 'settings', 'settings-outline', 'shield',
  'sparkles', 'sparkles-outline', 'time', 'trail-sign',
  'key', 'hand-left', 'search',
]

const dir = new URL('../node_modules/ionicons/dist/svg/', import.meta.url)
const out = {}
for (const name of [...new Set(NAMES)].sort()) {
  const raw = readFileSync(new URL(`${name}.svg`, dir), 'utf8')
  const inner = raw.match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1].trim()
  // The line weight becomes a class, so one CSS variable can thicken a small icon.
  out[name] = inner.replace(/ stroke-width="32"/g, ' class="ion-line"')
}
const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n')
writeFileSync(
  new URL('../src/components/ionicons.gen.ts', import.meta.url),
  `// Generated by scripts/gen-icons.mjs from Ionicons 7 (MIT). Do not edit by hand.\nexport const ION = {\n${body}\n} as const\n\nexport type IonName = keyof typeof ION\n`,
)
console.log(`wrote ${Object.keys(out).length} glyphs`)
